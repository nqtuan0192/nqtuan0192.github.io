export function savedLanguage(storage) {
  try {
    const preference = storage === undefined ? globalThis.localStorage : storage;
    return preference?.getItem("profile-language") === "vi" ? "vi" : "en";
  } catch { return "en"; }
}

export function translate(language, key, values = {}) {
  const text = messages[language]?.[key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? "{" + name + "}"));
}
